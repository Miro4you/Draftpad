import opencascade from 'replicad-opencascadejs';
import { setOC, drawRoundedRectangle, makeBox } from 'replicad';
import { createRequire } from 'node:module';
import { polyLoop, circleLoop } from '../src/curves.ts';
import { buildSolid } from '../src/model.ts';
const require = createRequire(import.meta.url);
const oc = await (opencascade as any)({ locateFile: () => require.resolve('replicad-opencascadejs/wasm') });
setOC(oc);
const T = (n: string, f: () => any) => { const t = performance.now(); try { const r = f(); console.log(n, 'ok', (performance.now()-t).toFixed(0), 'ms', r?.faces?.length ?? r); } catch (e: any) { console.log(n, 'FEHLER', (performance.now()-t).toFixed(0), 'ms', typeof e === 'number' ? oc.OCJS?.getStandard_FailureData?.(e)?.GetMessageString?.() : e?.message ?? e); } };
T('box fillet all', () => makeBox([0,0,0],[10,10,10]).fillet(1));
const base = buildSolid({ loops: [polyLoop([[0,0],[80,0],[80,40],[0,40]])], height: 8, fillet: 0 }).shape;
T('plate fillet all', () => base.fillet(1));
T('plate fillet z=0', () => base.fillet(1, (e: any) => e.inPlane('XY', 0)));
T('plate fillet either', () => base.fillet(1, (e: any) => e.either([(f: any) => f.inPlane('XY', 0), (f: any) => f.inPlane('XY', 8)])));
const holed = buildSolid({ loops: [polyLoop([[0,0],[80,0],[80,40],[0,40]]), circleLoop([20,20],4)], height: 8, fillet: 0 }).shape;
T('holed fillet z=0', () => holed.fillet(1, (e: any) => e.inPlane('XY', 0)));
T('holed fillet all', () => holed.fillet(1));
T('holed fillet 0.5 z=0', () => holed.fillet(0.5, (e: any) => e.inPlane('XY', 0)));
T('holed faces', () => holed);
const h2 = buildSolid({ loops: [polyLoop([[0,0],[80,0],[80,40],[0,40]]), circleLoop([20,20],4), circleLoop([60,20],4)], height: 8, fillet: 0 }).shape;
T('2holes faces', () => h2);
T('2holes fillet z0', () => h2.fillet(1, (e: any) => e.inPlane('XY', 0)));
T('2holes fillet either', () => h2.fillet(1, (e: any) => e.either([(f: any) => f.inPlane('XY', 0), (f: any) => f.inPlane('XY', 8)])));
T('2holes via build', () => buildSolid({ loops: [polyLoop([[0,0],[80,0],[80,40],[0,40]]), circleLoop([20,20],4), circleLoop([60,20],4)], height: 8, fillet: 1 }).shape);
T('2holes top only', () => h2.fillet(1, (e: any) => e.inPlane('XY', 8)));
T('2holes seq', () => h2.fillet(1, (e: any) => e.inPlane('XY', 0)).fillet(1, (e: any) => e.inPlane('XY', 8)));
T('2holes all', () => h2.fillet(1));
T('2holes top r0.5', () => h2.fillet(0.5, (e: any) => e.inPlane('XY', 8)));
const h2b = buildSolid({ loops: [polyLoop([[0,0],[80,0],[80,40],[0,40]]), circleLoop([20,20],4), circleLoop([60,20],5)], height: 8, fillet: 0 }).shape;
T('2holes diff r, top', () => h2b.fillet(1, (e: any) => e.inPlane('XY', 8)));
import { drawRectangle, drawCircle } from 'replicad';
const nat = (drawRectangle(80, 40).cut(drawCircle(4).translate(-20, 0)).cut(drawCircle(4).translate(20, 0)) as any).sketchOnPlane('XY').extrude(8);
T('native 2holes all', () => nat.fillet(1));
T('native faces', () => nat);
